#!/usr/bin/env python3
"""Generate src/text/font8x16.c (CP437 order, 8x16 glyphs) from a PSF console font.

Default sources: Uni2-VGA16.psf.gz, then FullGreek-VGA16.psf.gz for glyphs missing in the first
(/usr/share/consolefonts, Debian/Ubuntu console-setup). The VGA glyphs come from u_vga16.bdf,
Copyright (c) 2000, 2001 Dmitry Bolkhovityanov, MIT-style license.

usage: python3 tools/gen_font.py [font.psf[.gz] ...] > src/text/font8x16.c
"""
import gzip
import struct
import sys

# CP437 glyphs for the control range 0x00-0x1F and 0x7F (as drawn by the IBM PC)
CP437_LOW = "\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"


def cp437_unicode(code):
    if code < 0x20:
        return CP437_LOW[code]
    if code == 0x7F:
        return "⌂"
    return bytes([code]).decode("cp437")


def load_psf(path):
    raw = open(path, "rb").read()
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
    unicode_map = {}
    if raw[:2] == b"\x36\x04":  # PSF1
        mode, charsize = raw[2], raw[3]
        count = 512 if mode & 0x01 else 256
        glyphs = [raw[4 + i * charsize: 4 + (i + 1) * charsize] for i in range(count)]
        height, width = charsize, 8
        if mode & 0x02:
            pos = 4 + count * charsize
            for g in range(count):
                while True:
                    (u,) = struct.unpack_from("<H", raw, pos)
                    pos += 2
                    if u == 0xFFFF:
                        break
                    if u == 0xFFFE:
                        continue
                    unicode_map.setdefault(chr(u), g)
    elif raw[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        _, _, headersize, flags, count, charsize, height, width = struct.unpack_from("<8I", raw, 0)
        glyphs = [raw[headersize + i * charsize: headersize + (i + 1) * charsize] for i in range(count)]
        if flags & 0x01:
            pos = headersize + count * charsize
            for g in range(count):
                seq = bytearray()
                while raw[pos] != 0xFF:
                    seq.append(raw[pos])
                    pos += 1
                pos += 1
                for part in bytes(seq).split(b"\xfe")[:1]:
                    for ch in part.decode("utf-8", errors="ignore"):
                        unicode_map.setdefault(ch, g)
    else:
        raise SystemExit("not a PSF font")
    if width != 8 or height != 16:
        raise SystemExit("expected an 8x16 font, got %dx%d" % (width, height))
    return glyphs, unicode_map


# Alternative code points tried when a font lacks the canonical CP437 one
ALTERNATES = {"►": "▶", "◄": "◀", "•": "∙", "○": "◦", "⌂": "△"}


def main():
    paths = sys.argv[1:] or ["/usr/share/consolefonts/Uni2-VGA16.psf.gz",
                             "/usr/share/consolefonts/FullGreek-VGA16.psf.gz"]
    fonts = [load_psf(p) for p in paths]

    def lookup(ch):
        for candidate in (ch, ALTERNATES.get(ch)):
            if candidate is None:
                continue
            for glyphs, umap in fonts:
                if candidate in umap:
                    return glyphs[umap[candidate]]
        return None
    out = []
    out.append("// Generated by tools/gen_font.py from Uni2-VGA16 + FullGreek-VGA16 (console-setup), do not edit by hand.")
    out.append("// Glyph data: u_vga16.bdf, Copyright (c) 2000, 2001 Dmitry Bolkhovityanov.")
    out.append("// Permission is hereby granted, free of charge, to any person obtaining a copy of this")
    out.append("// software, to deal in the Software without restriction (MIT-style license).")
    out.append("#include \"header/text/font.h\"")
    out.append("")
    out.append("// 256 glyphs in IBM code page 437 order, 16 rows per glyph, MSB = leftmost pixel")
    out.append("const uint8_t font8x16[256][16] = {")
    missing = []
    for code in range(256):
        ch = cp437_unicode(code)
        data = None if code == 0 else lookup(ch)
        if data is None:
            data = bytes(16)
            if code != 0:
                missing.append(code)
        hexes = ", ".join("0x%02X" % b for b in data)
        label = "" if code < 0x20 or code == 0x7F else " '%s'" % ch if ch not in "\\" else " backslash"
        out.append("    {%s}, // 0x%02X%s" % (hexes, code, label))
    out.append("};")
    print("\n".join(out))
    if missing:
        print("missing glyphs: %s" % ", ".join("0x%02X" % m for m in missing), file=sys.stderr)


if __name__ == "__main__":
    main()
